#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{DeviceRecord, ReportMeta, Section, SystemReport};

    fn sample_report() -> SystemReport {
        let mut cpu = Section::new("CPU");
        cpu.push(DeviceRecord::new("CPU 0").with_field("Model", "Example CPU"));
        SystemReport {
            meta: ReportMeta {
                schema_version: 1,
                app_name: "HowAmI".into(),
                app_version: "0.1.0".into(),
                generated_at: "2026-01-01T00:00:00+00:00".into(),
                os: "test".into(),
                architecture: "x86_64".into(),
                elevated: true,
                privacy_notice: "test".into(),
            },
            sections: vec![cpu],
            warnings: vec![],
        }
    }

    #[test]
    fn text_report_contains_core_fields() {
        let text = render_text(&sample_report());
        assert!(text.contains("HowAmI"));
        assert!(text.contains("Report Schema        : 1"));
        assert!(text.contains("Example CPU"));
        assert!(text.contains("Collection Privilege : Administrator / root"));
    }

    #[test]
    fn formats_byte_counts_for_people() {
        assert_eq!(
            display_value("GPU Memory (Registry)", "VRAMBytes", "8589934592"),
            "8589934592 (8.00 GiB)"
        );
        assert_eq!(
            display_value("Storage", "size", "1099511627776"),
            "1099511627776 (1.00 TiB)"
        );
    }

    #[test]
    fn formats_network_rates() {
        assert_eq!(
            display_value("Network Adapters", "SpeedBitsPerSecond", "1000000000"),
            "1000000000 (1.00 Gbit/s)"
        );
        assert_eq!(
            display_value("Network Adapters", "speed", "2500"),
            "2500 Mbit/s (2.50 Gbit/s)"
        );
    }

    #[test]
    fn formats_linux_sensor_units() {
        assert_eq!(
            display_value("Hardware Sensors / hwmon", "temp1_input", "42500"),
            "42500 (42.50 °C)"
        );
        assert_eq!(
            display_value("Power / Battery", "energy_full", "60000000"),
            "60000000 (60.000 Wh)"
        );
    }

    #[test]
    fn labels_common_windows_hardware_codes() {
        assert_eq!(display_value("CPU", "ArchitectureCode", "9"), "9 (x64)");
        assert_eq!(
            display_value("Memory", "SMBIOSMemoryTypeCode", "34"),
            "34 (DDR5)"
        );
        assert_eq!(
            display_value("Memory", "FormFactorCode", "12"),
            "12 (SODIMM)"
        );
    }
}
