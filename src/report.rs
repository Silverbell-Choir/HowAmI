use crate::model::SystemReport;
use std::fmt::Write as _;

pub fn render_text(report: &SystemReport) -> String {
    let mut out = String::new();

    let _ = writeln!(
        out,
        "╔══════════════════════════════════════════════════════════════╗"
    );
    let _ = writeln!(
        out,
        "║                            HowAmI                            ║"
    );
    let _ = writeln!(
        out,
        "║              Computer Hardware & System Report              ║"
    );
    let _ = writeln!(
        out,
        "╚══════════════════════════════════════════════════════════════╝"
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "Generated At         : {}", report.meta.generated_at);
    let _ = writeln!(out, "Version              : {}", report.meta.app_version);
    let _ = writeln!(out, "Report Schema        : {}", report.meta.schema_version);
    let _ = writeln!(out, "OS                   : {}", report.meta.os);
    let _ = writeln!(out, "Architecture         : {}", report.meta.architecture);
    let _ = writeln!(
        out,
        "Collection Privilege : {}",
        if report.meta.elevated {
            "Administrator / root"
        } else {
            "Standard user"
        }
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "Privacy / 개인정보: {}", report.meta.privacy_notice);

    if !report.warnings.is_empty() {
        let _ = writeln!(out);
        let _ = writeln!(out, "[ WARNINGS / 경고 ]");
        for warning in &report.warnings {
            let _ = writeln!(out, "- {warning}");
        }
    }

    for section in &report.sections {
        let _ = writeln!(out);
        let _ = writeln!(
            out,
            "=============================================================="
        );
        let _ = writeln!(out, "[ {} ]", section.name);
        let _ = writeln!(
            out,
            "=============================================================="
        );

        if section.records.is_empty() {
            let _ = writeln!(out, "Not available / 데이터 없음");
            continue;
        }

        for (index, record) in section.records.iter().enumerate() {
            if index > 0 {
                let _ = writeln!(out);
            }
            let _ = writeln!(out, "-- {} --", record.label);

            if record.fields.is_empty() {
                let _ = writeln!(out, "Not available / 데이터 없음");
                continue;
            }

            let width = record
                .fields
                .keys()
                .map(|key| key.chars().count())
                .max()
                .unwrap_or(0)
                .min(36);

            for (key, value) in &record.fields {
                let display = display_value(&section.name, key, value);
                let _ = writeln!(out, "{key:width$} : {display}", width = width);
            }
        }
    }

    let _ = writeln!(out);
    let _ = writeln!(out, "Generated by HowAmI — Silverbell Choir");
    out
}

fn display_value(section: &str, key: &str, value: &str) -> String {
    if is_byte_field(section, key) {
        if let Ok(bytes) = value.trim().parse::<u64>() {
            return format!("{value} ({})", format_bytes(bytes));
        }
    }

    if key == "SpeedBitsPerSecond" {
        if let Ok(bits_per_second) = value.trim().parse::<u64>() {
            return format!("{value} ({})", format_bits_per_second(bits_per_second));
        }
    }

    if section == "Network Adapters" && key == "speed" {
        if let Ok(megabits) = value.trim().parse::<u64>() {
            return if megabits >= 1000 {
                format!("{value} Mbit/s ({:.2} Gbit/s)", megabits as f64 / 1000.0)
            } else {
                format!("{value} Mbit/s")
            };
        }
    }

    if section == "Hardware Sensors / hwmon" {
        if let Some(display) = format_hwmon_value(key, value) {
            return display;
        }
    }

    if section == "Power / Battery" {
        if let Some(display) = format_power_supply_value(key, value) {
            return display;
        }
    }

    if let Ok(code) = value.trim().parse::<u32>() {
        let label = match key {
            "ArchitectureCode" => processor_architecture_name(code),
            "MemoryTypeCode" => cim_memory_type_name(code),
            "SMBIOSMemoryTypeCode" => smbios_memory_type_name(code),
            "FormFactorCode" => memory_form_factor_name(code),
            _ => None,
        };
        if let Some(label) = label {
            return format!("{value} ({label})");
        }
    }

    value.to_string()
}

fn is_byte_field(section: &str, key: &str) -> bool {
    key.ends_with("Bytes") || (section == "Storage" && key.eq_ignore_ascii_case("size"))
}

fn format_hwmon_value(key: &str, value: &str) -> Option<String> {
    let raw = value.trim().parse::<i64>().ok()?;

    if key.starts_with("temp") && key.ends_with("_input") {
        return Some(format!("{value} ({:.2} °C)", raw as f64 / 1000.0));
    }
    if key.starts_with("fan") && key.ends_with("_input") {
        return Some(format!("{value} RPM"));
    }
    if key.starts_with("in") && key.ends_with("_input") {
        return Some(format!("{value} ({:.3} V)", raw as f64 / 1000.0));
    }
    if key.starts_with("curr") && key.ends_with("_input") {
        return Some(format!("{value} ({:.3} A)", raw as f64 / 1000.0));
    }
    if key.starts_with("power")
        && (key.ends_with("_input") || key.ends_with("_average") || key.ends_with("_highest"))
    {
        return Some(format!("{value} ({:.3} W)", raw as f64 / 1_000_000.0));
    }
    if key.starts_with("energy") && key.ends_with("_input") {
        return Some(format!("{value} ({:.3} J)", raw as f64 / 1_000_000.0));
    }
    if key.starts_with("humidity") && key.ends_with("_input") {
        return Some(format!("{value} ({:.2} %RH)", raw as f64 / 1000.0));
    }

    None
}

fn format_power_supply_value(key: &str, value: &str) -> Option<String> {
    let raw = value.trim().parse::<i64>().ok()?;

    if key == "capacity" {
        return Some(format!("{value} %"));
    }
    if key.starts_with("energy_") {
        return Some(format!("{value} ({:.3} Wh)", raw as f64 / 1_000_000.0));
    }
    if key.starts_with("charge_") {
        return Some(format!("{value} ({:.3} Ah)", raw as f64 / 1_000_000.0));
    }
    if key.starts_with("voltage_") {
        return Some(format!("{value} ({:.3} V)", raw as f64 / 1_000_000.0));
    }
    if key.starts_with("current_") {
        return Some(format!("{value} ({:.3} A)", raw as f64 / 1_000_000.0));
    }
    if key.starts_with("power_") {
        return Some(format!("{value} ({:.3} W)", raw as f64 / 1_000_000.0));
    }

    None
}

fn format_bytes(bytes: u64) -> String {
    const KIB: f64 = 1024.0;
    const MIB: f64 = KIB * 1024.0;
    const GIB: f64 = MIB * 1024.0;
    const TIB: f64 = GIB * 1024.0;
    let value = bytes as f64;

    if value >= TIB {
        format!("{:.2} TiB", value / TIB)
    } else if value >= GIB {
        format!("{:.2} GiB", value / GIB)
    } else if value >= MIB {
        format!("{:.2} MiB", value / MIB)
    } else if value >= KIB {
        format!("{:.2} KiB", value / KIB)
    } else {
        format!("{bytes} B")
    }
}

fn format_bits_per_second(bits: u64) -> String {
    let value = bits as f64;
    if value >= 1_000_000_000.0 {
        format!("{:.2} Gbit/s", value / 1_000_000_000.0)
    } else if value >= 1_000_000.0 {
        format!("{:.2} Mbit/s", value / 1_000_000.0)
    } else if value >= 1_000.0 {
        format!("{:.2} kbit/s", value / 1_000.0)
    } else {
        format!("{bits} bit/s")
    }
}

